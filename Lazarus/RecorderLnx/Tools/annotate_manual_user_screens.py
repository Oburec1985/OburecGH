def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def font_for(image: Image.Image):
    size = max(14, min(24, round(min(image.size) / 32)))
    return ImageFont.truetype(str(FONT_PATH), size) if FONT_PATH.exists() else ImageFont.load_default()


def draw_marker(draw: ImageDraw.ImageDraw, x: int, y: int, number: int, font) -> None:
    text = str(number)
    box = draw.textbbox((0, 0), text, font=font)
    radius = max(11, (box[3] - box[1]) // 2 + 5)
    draw.ellipse((x - radius, y - radius, x + radius, y + radius), fill="#fff000", outline="#e00000", width=2)
    draw.text((x - (box[2] - box[0]) / 2, y - (box[3] - box[1]) / 2 - box[1]), text, fill="#000000", font=font)


def save_elements(base_name: str, source_name: str, items) -> None:
    lines = [
        f"# {base_name}", "", f"Источник: `../юзер/{source_name}` (оригинал не изменяется).", "",
        "| № элемента | Назначение | Описание как работает | Клавиши |", "|---:|---|---|---|",
    ]
    for number, (_, _, purpose, description, keys) in enumerate(items, 1):
        lines.append(f"| {number} | {purpose} | {description} | {keys} |")
    (OUTPUT / f"{base_name}.elements.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    OUTPUT.mkdir(parents=True, exist_ok=True)
    before = {name: sha256(SOURCE / name) for name in SCREENS}
    index = ["# Ручные заполненные снимки", "", "| Снимок | PNG | Карта элементов |", "|---|---|---|"]
    for source_name, (base_name, items) in SCREENS.items():
        source_path = SOURCE / source_name
        if not source_path.exists():
            raise FileNotFoundError(source_path)
        with Image.open(source_path) as source_image:
            image = source_image.convert("RGB")
        draw = ImageDraw.Draw(image)
        font = font_for(image)
        for number, (x, y, *_rest) in enumerate(items, 1):
            draw_marker(draw, x, y, number, font)
        image.save(OUTPUT / f"{base_name}.png", optimize=True)
        save_elements(base_name, source_name, items)
        index.append(f"| {source_name} | [{base_name}.png]({base_name}.png) | [{base_name}.elements.md]({base_name}.elements.md) |")
    after = {name: sha256(SOURCE / name) for name in SCREENS}
    if before != after:
        raise RuntimeError("A source screenshot changed during annotation")
    manifest = [f"{before[name]}  {name}" for name in sorted(before)]
    (OUTPUT / "source-sha256.txt").write_text("\n".join(manifest) + "\n", encoding="utf-8")
    (OUTPUT / "index.md").write_text("\n".join(index) + "\n", encoding="utf-8")
    print(f"Created {len(SCREENS)} annotated copies in {OUTPUT}")


if __name__ == "__main__":
    main()
